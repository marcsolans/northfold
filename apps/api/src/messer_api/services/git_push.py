"""Apply a ``git push`` to a project repository (the CLI path of "everything is code").

A push to the project's default branch is merged into the Messer repository exactly like a GitHub pull
(:mod:`messer_api.services.github`): the changed workforce members are re-parsed (code wins when the Studio
configuration cannot be derived) and versioned, here with ``source="cli"`` and the pushing user as author.

Merge policy for ``refs/heads/<default>`` (decided under the repository lock):

* fast-forward of Messer's head → accepted;
* the push is behind Messer (it would drop Messer commits) → rejected, ``git pull`` first;
* diverged histories (a forced push, or the Studio committed meanwhile) → merged with a merge commit when the
  merge is clean, rejected listing the conflicting paths otherwise. Messer commits are never lost;
* the only exception: a project whose single commit is the scaffold generated by the CLI project-creation
  endpoint is replaced by the pushed history (the first ``messer push`` of a local project).

Deleting the default branch is never allowed. Other branches are refused; tags can be created and deleted.
"""

