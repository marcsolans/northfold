from . import github as github_svc
from .projects import author_for

log = get_logger("messer.api.git_push")

ZERO_SHA = "0" * 40
DEFAULT_BRANCH = "main"
SCAFFOLD_AUTHOR = "Messer"
SCAFFOLD_EMAIL = "noreply@messer.local"
SCAFFOLD_MESSAGE = "Initial scaffold"
MAX_BLOB_BYTES = 25 * 1024 * 1024
MAX_FILES = 20_000
PUSH_LOCK_TIMEOUT_S = 600

Outcome = Literal["up_to_date", "fast_forward", "merge", "replace"]


class PushRejected(Exception):
    """A ref update is refused; ``reason`` is shown to the git client (``! [remote rejected] … (reason)``)."""

    def __init__(self, reason: str) -> None:
        super().__init__(reason)
        self.reason = reason.replace("\n", " ").strip()


@dataclass(slots=True)
class RefUpdate:
    old: str
    new: str
    ref: str


@dataclass(slots=True)
class RefResult:
    ref: str
    error: str | None = None


@dataclass(slots=True)
class PushReport:
    results: list[RefResult] = field(default_factory=list)
    messages: list[str] = field(default_factory=list)
    summary: dict[str, Any] | None = None


# --------------------------------------------------------------------------------------------- git plumbing


def git_env(extra: dict[str, str] | None = None) -> dict[str, str]:
    env = {
        **os.environ,
        "GIT_TERMINAL_PROMPT": "0",
        "GIT_CONFIG_NOSYSTEM": "1",
        "HOME": str(get_settings().projects_dir),
    }
    for key in (
        "GIT_DIR",
        "GIT_WORK_TREE",
        "GIT_INDEX_FILE",
        "GIT_OBJECT_DIRECTORY",
        "GIT_ALTERNATE_OBJECT_DIRECTORIES",
    ):
        env.pop(key, None)
    if extra:
        env.update(extra)
    return env


async def git(
    repo: ProjectRepo, *args: str, env: dict[str, str] | None = None, input_bytes: bytes | None = None
) -> tuple[int, bytes, bytes]:
    proc = await asyncio.create_subprocess_exec(
        "git",
        "-c",
        "core.quotepath=off",
        "-c",
        "commit.gpgsign=false",
        *args,
        cwd=repo.path,
        env=env or git_env(),
        stdin=asyncio.subprocess.PIPE if input_bytes is not None else asyncio.subprocess.DEVNULL,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    try:
        out, err = await asyncio.wait_for(proc.communicate(input_bytes), timeout=300)
    except TimeoutError:
        proc.kill()
        await proc.wait()
        raise RepoError(f"git {args[0]} timed out") from None
    return proc.returncode or 0, out, err


async def git_ok(repo: ProjectRepo, *args: str, env: dict[str, str] | None = None) -> str:
    code, out, err = await git(repo, *args, env=env)
    if code != 0:
        raise RepoError(f"git {args[0]} failed: {err.decode(errors='replace').strip()}")
    return out.decode(errors="replace").strip()


async def is_ancestor(repo: ProjectRepo, ancestor: str, descendant: str, env: dict[str, str] | None = None) -> bool:
    code, _, err = await git(repo, "merge-base", "--is-ancestor", ancestor, descendant, env=env)
    if code not in (0, 1):
        raise RepoError(f"git merge-base failed: {err.decode(errors='replace').strip()}")
    return code == 0


async def object_type(repo: ProjectRepo, sha: str, env: dict[str, str] | None = None) -> str | None:
    code, out, _ = await git(repo, "cat-file", "-t", sha, env=env)
    return out.decode().strip() if code == 0 else None


async def default_branch(repo: ProjectRepo) -> str:
    code, out, _ = await git(repo, "symbolic-ref", "--short", "HEAD")
    branch = out.decode().strip() if code == 0 else ""
    return branch or DEFAULT_BRANCH


async def vet_tree(repo: ProjectRepo, sha: str, env: dict[str, str] | None = None) -> None:
    """Refuse trees Messer cannot run safely (same rules as the GitHub sync): symlinks, submodules, huge files."""
    out = await git_ok(repo, "ls-tree", "-r", "-l", "--full-tree", "-z", sha, env=env)
    records = [r for r in out.split("\0") if r]
    if len(records) > MAX_FILES:
        raise PushRejected(f"el proyecto tiene más de {MAX_FILES} archivos")
    for record in records:
        meta, _, path = record.partition("\t")
        mode, kind, _obj, size = meta.split(maxsplit=3)
        if mode == "120000":
            raise PushRejected(f"Messer no admite enlaces simbólicos: {path}")
        if mode == "160000" or kind == "commit":
            raise PushRejected(f"Messer no admite submódulos: {path}")
        if size.strip().isdigit() and int(size) > MAX_BLOB_BYTES:
            raise PushRejected(f"el archivo {path} supera 25 MB")


async def is_cli_scaffold(repo: ProjectRepo, sha: str) -> bool:
    """True when ``sha`` is the untouched single commit created by ``POST /orgs/{org}/projects`` (CLI)."""
    code, out, _ = await git(repo, "log", "-2", "--format=%P%x1f%s%x1f%ae", sha)
    if code != 0:
        return False
    lines = [line for line in out.decode(errors="replace").splitlines() if line]
    if len(lines) != 1:
        return False
    parents, subject, email = lines[0].split("\x1f")
    return not parents.strip() and subject == SCAFFOLD_MESSAGE and email == SCAFFOLD_EMAIL


# ------------------------------------------------------------------------------------------ ref updates


async def apply_push(
    project_id: uuid.UUID,
    principal: Principal,
    updates: list[RefUpdate],
    *,
    atomic: bool = False,
    object_env: dict[str, str] | None = None,
    on_accepted: Callable[[], None] | None = None,
) -> PushReport:
    """Validate and apply ``updates``. For validation the pushed objects are read through ``object_env`` (the
    quarantine); ``on_accepted`` (moving them into the repository) runs once at least one update passes the
    checks, before anything is applied. Returns one result per update plus progress messages for the client."""
    repo = ProjectRepo.for_project(str(project_id))
    report = PushReport()
    branch = await default_branch(repo)
    head_ref = f"refs/heads/{branch}"
    checked: list[tuple[RefUpdate, str | None]] = []
    for update in updates:
        try:
            await _precheck(repo, update, head_ref, object_env)
            checked.append((update, None))
        except PushRejected as exc:
            checked.append((update, exc.reason))
    if atomic and any(error for _, error in checked):
        report.results = [
            RefResult(u.ref, error or "push atómico rechazado: otra referencia ha fallado") for u, error in checked
        ]
        return report
    if on_accepted is not None and any(error is None for _, error in checked):
        on_accepted()

    lock = get_redis().lock(f"git-push:{project_id}", timeout=PUSH_LOCK_TIMEOUT_S, blocking_timeout=30)
    if not await lock.acquire():
        report.results = [RefResult(u.ref, "otro push está en curso; vuelve a intentarlo") for u in updates]
        return report
    try:
        for update, error in checked:
            if error is not None:
                report.results.append(RefResult(update.ref, error))
                continue
            try:
                if update.ref == head_ref:
                    await _update_branch(repo, project_id, principal, update, branch, report)
                else:
                    await _update_tag(repo, update)
                report.results.append(RefResult(update.ref))
            except PushRejected as exc:
                report.results.append(RefResult(update.ref, exc.reason))
            except RepoError as exc:
                log.warning("git_push.failed", project_id=str(project_id), ref=update.ref, error=str(exc))
                report.results.append(RefResult(update.ref, "error interno de Messer al aplicar el push"))
    finally:
        try:
            await lock.release()
        except Exception:  # the lock expired: nothing to release
            log.warning("git_push.lock_release_failed", project_id=str(project_id))
    return report


async def _precheck(repo: ProjectRepo, update: RefUpdate, head_ref: str, env: dict[str, str] | None) -> None:
    if update.ref == head_ref:
        if update.new == ZERO_SHA:
            raise PushRejected(f"no se puede borrar la rama {head_ref.removeprefix('refs/heads/')} del proyecto")
        if await object_type(repo, update.new, env) != "commit":
            raise PushRejected("el push no contiene el commit indicado")
        await vet_tree(repo, update.new, env)
        return
    if update.ref.startswith("refs/heads/"):
        branch = head_ref.removeprefix("refs/heads/")
        raise PushRejected(f"Messer solo acepta pushes a la rama {branch}; fusiona tu rama y vuelve a intentarlo")
    if not update.ref.startswith("refs/tags/"):
        raise PushRejected("referencia no admitida (solo la rama principal y etiquetas)")
    code, _, _ = await git(repo, "check-ref-format", update.ref)
    if code != 0:
        raise PushRejected("nombre de etiqueta no válido")
    if update.old != ZERO_SHA and update.new != ZERO_SHA:
        raise PushRejected("las etiquetas no se pueden mover; crea una nueva")
    if update.new != ZERO_SHA and await object_type(repo, update.new, env) is None:
        raise PushRejected("el push no contiene el objeto de la etiqueta")


async def _update_tag(repo: ProjectRepo, update: RefUpdate) -> None:
    if update.new == ZERO_SHA:
        code, _, _ = await git(repo, "update-ref", "-d", update.ref, update.old)
    else:
        code, _, _ = await git(repo, "update-ref", update.ref, update.new, ZERO_SHA)
    if code != 0:
        raise PushRejected("la etiqueta ha cambiado en Messer; actualiza y vuelve a intentarlo")


async def _update_branch(
    repo: ProjectRepo,
    project_id: uuid.UUID,
    principal: Principal,
    update: RefUpdate,
    branch: str,
    report: PushReport,
) -> None:
    async with system_session() as s:
        author = await author_for(s, principal)
    async with _locks[str(repo.path)]:
        if await git_ok(repo, "status", "--porcelain"):
            raise RepoError("the working tree has uncommitted changes")
        old_head = await git_ok(repo, "rev-parse", "HEAD")
        outcome, new_head, conflicts = await _merge(repo, old_head, update.new, branch, author.name, author.email)
        if outcome == "up_to_date":
            report.messages.append("Messer: el proyecto ya estaba al día.")
            return
        try:
            summary = await apply_changes(
                project_id, principal, old_head=old_head, new_head=new_head, pushed=update.new, outcome=outcome
            )
        except Exception:
            # Never leave the repository ahead of the database: undo the ref update and report the failure.
            await git(repo, "reset", "--hard", "--quiet", old_head)
            log.exception("git_push.apply_failed", project_id=str(project_id))
            raise RepoError("the database update failed") from None
    report.summary = summary
    report.messages.extend(_messages(outcome, new_head, summary, conflicts))
    await repo._notify_commit(new_head)  # e.g. the GitHub sync pushes the new head to the connected repository


async def _merge(
    repo: ProjectRepo, head: str, new: str, branch: str, name: str, email: str
) -> tuple[Outcome, str, list[str]]:
    if new == head:
        return "up_to_date", head, []
    if await is_ancestor(repo, head, new):
        await git_ok(repo, "merge", "--ff-only", "--quiet", new)
        return "fast_forward", new, []
    if await is_ancestor(repo, new, head):
        raise PushRejected("Messer tiene commits que tu rama no incluye; ejecuta git pull y vuelve a intentarlo")
    if await is_cli_scaffold(repo, head):
        await git_ok(repo, "reset", "--hard", "--quiet", new)
        return "replace", new, []
    code, out, _ = await git(
        repo,
        "merge-tree",
        "--write-tree",
        "--name-only",
        "--no-messages",
        "--allow-unrelated-histories",
        head,
        new,
    )
    if code == 1:
        lines = out.decode(errors="replace").splitlines()
        conflicts = sorted({line for line in lines[1:] if line.strip()})
        shown = ", ".join(conflicts[:5]) + ("…" if len(conflicts) > 5 else "")
        raise PushRejected(f"conflicto con cambios hechos en Messer ({shown}); ejecuta git pull, resuelve y reintenta")
    if code != 0:
        raise RepoError("git merge-tree failed")
    message = f"Merge push into {branch}\n\nThe pushed history is merged with changes made in Messer meanwhile."
    code, _, err = await git(
        repo,
        "-c",
        f"user.name={name}",
        "-c",
        f"user.email={email}",
        "merge",
        "--no-ff",
        "--no-edit",
        "--quiet",
        "--allow-unrelated-histories",
        "-m",
        message,
        new,
    )
    if code != 0:
        await git(repo, "merge", "--abort")
        raise RepoError(f"git merge failed: {err.decode(errors='replace').strip()}")
    return "merge", await git_ok(repo, "rev-parse", "HEAD"), []


def _messages(outcome: Outcome, head: str, summary: dict[str, Any], conflicts: list[str]) -> list[str]:
    out: list[str] = []
    if outcome == "merge":
        out.append(
            f"Messer: tu push se ha fusionado con cambios recientes de Messer (commit {head[:12]}). "
            "Ejecuta git pull para sincronizar tu copia."
        )
    elif outcome == "replace":
        out.append("Messer: historial importado sobre el proyecto recién creado.")
    for key, label in (("created", "creados"), ("updated", "nuevas versiones"), ("deleted", "eliminados")):
        names = summary.get(key) or []
        if names:
            out.append(f"Messer: {label}: {', '.join(names)}")
    for name in summary.get("ignored") or []:
        out.append(f"Messer: ignorado workforce/{name} (nombre no válido: minúsculas, números y _)")
    if summary.get("project_version"):
        out.append(f"Messer: versión de proyecto v{summary['project_version']} lista para desplegar (messer deploy).")
    out.extend(f"Messer: conflicto resuelto en {path}" for path in conflicts)
    return out


# ------------------------------------------------------------------------------- incoming → database


async def apply_changes(
    project_id: uuid.UUID,
    principal: Principal,
    *,
    old_head: str,
    new_head: str,
    pushed: str,
    outcome: str,
) -> dict[str, Any]:
    """Sync the workforce members changed between ``old_head`` and ``new_head`` into the database (versions with
    ``source="cli"``, a project version, audit and notifications) in one transaction."""
    repo = ProjectRepo.for_project(str(project_id))
    changed = await repo.changed_files(old_head, new_head)
    names = sorted({p.split("/")[1] for p in changed if p.startswith("workforce/") and p.count("/") >= 2})
    tip = await repo.commit_info(pushed)
    summary: dict[str, Any] = {
        "commit": new_head,
        "pushed": pushed,
        "outcome": outcome,
        "files": len(changed),
        "created": [],
        "updated": [],
        "deleted": [],
        "ignored": [],
    }
    async with system_session() as s:
        project = await s.get(Project, project_id)
        if project is None:
            raise RepoError("project not found")
        for name in names:
            if not github_svc._valid_member_name(name):
                summary["ignored"].append(name)
                continue
            await _sync_member(s, repo, project, principal, name, new_head, tip.message, summary)
        number = await github_svc._next_version(s, "project", project.id)
        s.add(
            Version(
                org_id=project.org_id,
                project_id=project.id,
                entity_type="project",
                entity_id=project.id,
                version=number,
                git_commit=new_head,
                snapshot_json={"files": await repo.list_files(new_head), "cli": {"pushed": pushed, "outcome": outcome}},
                author_id=principal.user_id,
                message=f"Push: {tip.message}"[:500],
                source="cli",
            )
        )
        summary["project_version"] = number
        await audit.record(
            s,
            action="git.pushed",
            principal=principal,
            org_id=project.org_id,
            entity_type="project",
            entity_id=project.id,
            diff={
                "commit": new_head,
                "pushed": pushed,
                "previous": old_head,
                "outcome": outcome,
                "created": summary["created"],
                "updated": summary["updated"],
                "deleted": summary["deleted"],
            },
        )
        await _notify(s, project, principal, summary)
    return summary


async def _sync_member(
    s: AsyncSession,
    repo: ProjectRepo,
    project: Project,
    principal: Principal,
    name: str,
    head: str,
    subject: str,
    summary: dict[str, Any],
) -> None:
    base = f"workforce/{name}"
    member = (
        await s.execute(select(Workforce).where(Workforce.project_id == project.id, Workforce.name == name))
    ).scalar_one_or_none()
    manifest_raw = await repo.read(f"{base}/messer.yaml", head)
    try:
        manifest = yaml.safe_load(manifest_raw) if manifest_raw else {}
    except yaml.YAMLError:
        manifest = {}
    manifest = manifest if isinstance(manifest, dict) else {}
    files = set(await repo.list_files(head, prefix=f"{base}/"))
    kind = str(manifest.get("_type") or "")
    if kind not in ("agent", "workflow"):
        kind = "agent" if f"{base}/agent.py" in files else ("workflow" if f"{base}/workflow.py" in files else "")
    code_file = f"{base}/{'agent.py' if kind == 'agent' else 'workflow.py'}" if kind else ""
    if not kind or code_file not in files:
        if member is not None:
            await s.delete(member)
            summary["deleted"].append(name)
            await audit.record(
                s,
                action="workforce.deleted",
                principal=principal,
                org_id=project.org_id,
                entity_type="workforce",
                entity_id=member.id,
                diff={"name": name, "source": "cli"},
            )
        return
    code = await repo.read(code_file, head) or ""
    config: dict[str, Any] | None = None
    if kind == "agent":
        parsed = parse_agent_code(code)
        if parsed is not None and parsed.name == name:
            config = parsed.model_dump(mode="json")
    else:
        config = github_svc._parse_workflow(code)
    source_mode = "config" if config is not None else "code"
    created = member is None
    if member is None:
        member_id = uuid.uuid4()
        raw_id = manifest.get("_id")
        try:
            candidate = uuid.UUID(str(raw_id)) if raw_id else None
        except ValueError:
            candidate = None
        if candidate is not None and await s.get(Workforce, candidate) is None:
            member_id = candidate
        member = Workforce(
            id=member_id,
            org_id=project.org_id,
            project_id=project.id,
            kind=kind,
            name=name,
            description=str((config or {}).get("description") or ""),
            path=base,
            config_json=config or {},
            source_mode=source_mode,
        )
        s.add(member)
        await s.flush()
        summary["created"].append(name)
    else:
        member.kind = kind
        member.source_mode = source_mode
        if config is not None:
            member.config_json = config
            if config.get("description") is not None:
                member.description = str(config["description"])
        summary["updated"].append(name)
    number = await github_svc._next_version(s, "workforce", member.id)
    s.add(
        Version(
            org_id=project.org_id,
            project_id=project.id,
            entity_type="workforce",
            entity_id=member.id,
            version=number,
            git_commit=head,
            snapshot_json={"config": member.config_json, "code": code, "source_mode": source_mode},
            author_id=principal.user_id,
            message=f"Push: {subject}"[:500],
            source="cli",
        )
    )
    member.current_version = number
    await audit.record(
        s,
        action="workforce.created" if created else "workforce.version_saved",
        principal=principal,
        org_id=project.org_id,
        entity_type="workforce",
        entity_id=member.id,
        diff={"name": name, "version": number, "commit": head, "source": "cli", "source_mode": source_mode},
    )


async def _notify(s: AsyncSession, project: Project, principal: Principal, summary: dict[str, Any]) -> None:
    members = [*summary["created"], *summary["updated"], *summary["deleted"]]
    user = await s.get(User, principal.user_id) if principal.user_id else None
    who = (user.name or user.email) if user is not None else (principal.email or "Un desarrollador")
    if members:
        body = f"{who} ha enviado cambios con git push: {', '.join(members[:5])}" + ("…" if len(members) > 5 else "")
    else:
        body = f"{who} ha enviado cambios con git push ({summary['files']} archivos)"
    url = f"{get_settings().messer_web_url.rstrip('/')}/app/projects/{project.id}"
    rows = (
        await s.execute(select(Membership.role, Membership.user_id).where(Membership.org_id == project.org_id))
    ).all()
    for role, user_id in rows:
        if user_id == principal.user_id or not at_least(role, "builder"):
            continue
        s.add(
            Notification(
                org_id=project.org_id,
                user_id=user_id,
                kind="git_push",
                payload={
                    "title": f"Cambios por git push en «{project.name}»",
                    "body": body,
                    "url": url,
                    "project_id": str(project.id),
                    "commit": summary["commit"],
                },
            )
        )
