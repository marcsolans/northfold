def eval_shim(member: str) -> str:
    """Entry point for an agent's evals that imports it as part of the project package (``tools.py`` and other
    relative imports resolve exactly as in the sandbox; loading ``agent.py`` by path would break them)."""
    return (
        f'"""Eval entry point for «{member}» (generated by the Messer Composer)."""\n\n'
        f"from workforce.{member}.agent import agent\n\n"
        '__all__ = ["agent"]\n'
    )


EVAL_SHIM_FILE = "_composer_target.py"


def eval_entries(member: str, kind: str, evals: list[PlanEval], *, offline: bool) -> list[dict[str, Any]]:
    """Engine YAML eval cases for the plan's acceptance evals of one member."""
    runnable = f"{EVAL_SHIM_FILE}::agent" if kind == "agent" else "../workflow.py::workflow"
    out: list[dict[str, Any]] = []
    for e in evals:
        case: dict[str, Any] = {
            "name": f"{member}__{e.name}",
            "description": f"Composer: {e.expect}{(' ' + e.value) if e.value else ''}",
            "runnable": runnable,
            "tags": [EVAL_TAG, "llm" if e.expect == "rubric" else "offline"],
            "params": dict(e.input),
        }
        if e.expect == "rubric":
            if offline:
                continue  # graded by a model: added when a provider key is configured
            case["output"] = {"rubric!": e.value or "La respuesta resuelve la petición del usuario"}
        elif e.expect == "contains":
            if kind == "workflow" and "=" in e.value:
                key, _, expected = e.value.partition("=")
                case["output"] = {key.strip(): {"eq!": _scalar(expected.strip())}}
            elif kind == "workflow":
                case["output"] = {"contains!": e.value}
            else:
                case["output"] = {"contains!": {"value": e.value, "transform": "lowercase"}}
        elif e.expect == "not_contains":
            case["output"] = (
                {"not_contains!": {"value": e.value, "transform": "lowercase"}}
                if kind == "agent"
                else ({"not_contains!": e.value})
            )
        elif e.expect == "tool_called":
            case["seq!"] = ["...", e.value, "..."]
        elif e.expect == "approval_required":
            case["output"] = {"status": {"eq!": "approval_required"}}
        else:  # min_length
            try:
                minimum = max(1, int(float(e.value or "1")))
            except ValueError:
                minimum = 1
            case["output"] = {"min_length!": minimum}
        out.append(case)
    return out


def _scalar(value: str) -> Any:
    if value.lower() in ("true", "false"):
        return value.lower() == "true"
    try:
        number = float(value)
    except ValueError:
        return value
    return int(number) if number.is_integer() else number


def evals_yaml(cases: list[dict[str, Any]]) -> str:
    header = "# Acceptance evals from the Composer plan (deterministic validators pass with the demo model).\n"
    return header + yaml.safe_dump(cases, allow_unicode=True, sort_keys=False, default_flow_style=False)
