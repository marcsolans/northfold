@dataclass
class Resolved:
    """What exists in the project when a section is compiled (ids and schemas the plan only names)."""

    kb_ids: dict[str, str] = field(default_factory=dict)  # plan KB name → knowledge base id
    tables: dict[str, list[dict[str, Any]]] = field(default_factory=dict)  # "kb.table" → [{"name", "type"}]
    members: dict[str, str] = field(default_factory=dict)  # workforce name → "agent" | "workflow"
    workflow_inputs: dict[str, list[WorkflowInput]] = field(default_factory=dict)
    workflow_descriptions: dict[str, str] = field(default_factory=dict)
    connector_actions: dict[str, dict[str, Any]] = field(default_factory=dict)  # "conn.action" → tool spec
    agent_greetings: dict[str, str] = field(default_factory=dict)


