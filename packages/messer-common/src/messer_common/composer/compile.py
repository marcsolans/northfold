def linked_workflows(agent: PlanAgent, workflows: list[PlanWorkflow]) -> list[str]:
    """Workflows the agent can start as a tool: named in its approval rules or in its instructions."""
    names = {w.name for w in workflows}
    out = [r.action for r in agent.approvals if r.action in names]
    text = fold(agent.instructions)
    for wf in workflows:
        if wf.name in out:
            continue
        if wf.trigger.kind == "manual" and (wf.name in agent.instructions or fold(wf.title) in text):
            out.append(wf.name)
    return list(dict.fromkeys(out))


def tools_module(agent_name: str, workflows: list[str]) -> str:
    """``tools.py`` exposing workflows of the project as tools of the agent (approvals inside them still apply)."""
    lines = [
        f'"""Tools of «{agent_name}» generated by the Messer Composer.',
        "",
        "Each tool is a workflow of this project: the agent calls it with the workflow's inputs, and any human",
        'approval inside the workflow pauses the conversation until someone decides."""',
        "",
    ]
    for wf in workflows:
        lines.append(f"from ..{wf}.workflow import workflow as {wf}")
    lines += ["", f"__all__ = {sorted(workflows)!r}", ""]
    return "\n".join(lines).replace("'", '"')


def _approval_lines(agent: PlanAgent, en: bool) -> list[str]:
    lines: list[str] = []
    for rule in agent.approvals:
        if rule.action and rule.action in agent.instructions:
            continue
        when = rule.condition or (f"over {format_eur(rule.threshold)}" if (rule.threshold and en) else "")
        if en:
            lines.append(
                f"Before {rule.action.replace('_', ' ')}{(' (' + when + ')') if when else ''}, a person "
                f"with the {rule.approver_role} role must approve it."
            )
        else:
            lines.append(
                f"Antes de {rule.action.replace('_', ' ')}{(' (' + when + ')') if when else ''} debe "
                f"aprobarlo una persona con rol {rule.approver_role}."
            )
    return lines


def system_prompt(agent: PlanAgent) -> str:
    en = detect_language(agent.instructions or agent.description) == "en"
    head = f"You are «{agent.title}». {agent.description}" if en else f"Eres «{agent.title}». {agent.description}"
    parts = [head.strip(), agent.instructions.strip(), *_approval_lines(agent, en)]
    return "\n\n".join(p for p in parts if p)


def agent_config(
    agent: PlanAgent,
    *,
    resolved: Resolved,
    workflows: list[str],
    warnings: list[str],
) -> AgentConfig:
    """Studio configuration of a plan agent (knowledge bases, tools, approvals, voice, greeting)."""
    kb_ids = [resolved.kb_ids[k] for k in agent.knowledge if k in resolved.kb_ids]
    for missing in [k for k in agent.knowledge if k not in resolved.kb_ids]:
        warnings.append(f"{agent.name}: la base de conocimiento «{missing}» no existe")
    rules: dict[str, ApprovalRule] = {r.action: r for r in agent.approvals}
    tools: list[ToolConfig] = []
    for key in dict.fromkeys(agent.tools):
        if key in ("knowledge_search", "sql_query") and not kb_ids:
            warnings.append(f"{agent.name}: «{key}» necesita una base de conocimiento; no se ha añadido")
            continue
        rule = rules.get(key)
        tools.append(
            ToolConfig(
                type="builtin",
                key=key,
                requires_approval=key in SIDE_EFFECT_TOOLS or rule is not None,
                approver_role=rule.approver_role if rule else "admin",
                config={"kb_id": kb_ids[0]} if key == "sql_query" else {},
            )
        )
    for ref in agent.connector_actions:
        spec = resolved.connector_actions.get(ref)
        if spec is None:
            warnings.append(f"{agent.name}: la acción de conector «{ref}» necesita una conexión activa")
            continue
        action = ref.split(".", 1)[1] if "." in ref else ref
        rule = rules.get(action) or rules.get(ref)
        tools.append(
            ToolConfig(
                type="connector",
                key=action,
                name=re.sub(r"[^a-zA-Z0-9_]", "_", ref)[:60],
                connection_id=str(spec["connection_id"]),
                description=str(spec.get("description") or ""),
                input_schema=spec.get("input_schema") or {"type": "object", "properties": {}},
                requires_approval=bool(spec.get("side_effect")) or rule is not None,
                approver_role=rule.approver_role if rule else "admin",
            )
        )
    for wf in workflows:
        tools.append(
            ToolConfig(
                type="custom",
                key=wf,
                description=resolved.workflow_descriptions.get(wf, "")[:500],
            )
        )
    if not any(t.key == "current_datetime" for t in tools):
        tools.append(ToolConfig(type="builtin", key="current_datetime"))
    language = "en" if detect_language(agent.instructions or agent.description) == "en" else "es"
    return AgentConfig(
        name=agent.name,
        description=agent.description[:500],
        model_tier=agent.model_tier,
        system_prompt=system_prompt(agent),
        tools=tools,
        knowledge_bases=kb_ids,
        guardrails=[GuardrailConfig(type="injection", mode="enforce"), GuardrailConfig(type="pii", mode="shadow")],
        memory=MemoryConfig(),
        voice=VoiceConfig(enabled=agent.voice, language=language, greeting=agent.greeting[:1000]),
    )


