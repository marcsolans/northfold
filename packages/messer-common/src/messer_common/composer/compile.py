def _field_name(raw: Any) -> str | None:
    name = raw.get("name") if isinstance(raw, dict) else raw
    if not isinstance(name, str) or not name.strip():
        return None
    return ident(name, fallback="campo")


def _inputs(wf: PlanWorkflow) -> list[WorkflowInput]:
    names: list[str] = []
    descriptions: dict[str, str] = {}
    types: dict[str, str] = {}
    for step in wf.steps:
        if step.kind != "input":
            continue
        for raw in step.config.get("fields") or step.config.get("inputs") or []:
            name = _field_name(raw)
            if name:
                names.append(name)
                if isinstance(raw, dict):
                    descriptions[name] = str(raw.get("description") or "")
                    if raw.get("type") in ("string", "number", "boolean", "object"):
                        types[name] = str(raw["type"])
    blob = " ".join(str(s.config) for s in wf.steps)
    for match in re.findall(r"\{\{\s*input\.([a-z][a-z0-9_]*)", blob):
        names.append(match)
    for rule in wf.approvals:
        if rule.field:
            names.append(ident(rule.field, fallback="campo"))
    if not names:
        names = ["mensaje"]
    out: list[WorkflowInput] = []
    for i, name in enumerate(dict.fromkeys(names)):
        if name in ("event", "input"):
            continue
        kind = types.get(name) or ("number" if name in NUMERIC_INPUTS or name.startswith("importe") else "string")
        out.append(
            WorkflowInput(
                name=name,
                type=kind,  # type: ignore[arg-type]
                description=descriptions.get(name) or name.replace("_", " ").capitalize(),
                required=i < 2,
            )
        )
    return out


def _payload(inputs: list[WorkflowInput]) -> dict[str, Any]:
    return {i.name: f"{{{{input.{i.name}}}}}" for i in inputs}


def _first_text_input(inputs: list[WorkflowInput]) -> str:
    name = next((i.name for i in inputs if i.type == "string"), inputs[0].name if inputs else "mensaje")
    return f"{{{{input.{name}}}}}"


def _rule_for(wf: PlanWorkflow, step: PlanStep) -> ApprovalRule | None:
    return next((r for r in wf.approvals if r.action == step.id), wf.approvals[0] if wf.approvals else None)


def _node(
    wf: PlanWorkflow,
    step: PlanStep,
    *,
    inputs: list[WorkflowInput],
    previous: list[PlanStep],
    resolved: Resolved,
    warnings: list[str],
) -> WorkflowNode:
    cfg = dict(step.config)
    label = step.title[:120]
    kind = step.kind
    en = detect_language(f"{wf.title} {wf.description}") == "en"

    def fallback(reason: str) -> WorkflowNode:
        warnings.append(f"{wf.name}.{step.id}: {reason}; se ha dejado como paso de preparación")
        return WorkflowNode(id=step.id, type="transform", label=label, config={"value": _payload(inputs)})

    def kb(value: Any) -> str | None:
        if isinstance(value, str) and value in resolved.kb_ids:
            return resolved.kb_ids[value]
        if isinstance(value, str) and re.fullmatch(r"[0-9a-f-]{36}", value):
            return value
        return next(iter(resolved.kb_ids.values()), None)

    if kind == "input":
        return WorkflowNode(id=step.id, type="input", label=label)
    if kind == "output":
        value = cfg.get("value")
        if value is None:
            value = {"estado": "completed" if en else "completado", **_payload(inputs)}
        return WorkflowNode(id=step.id, type="output", label=label, config={"value": value})
    if kind == "transform":
        value = cfg.get("value")
        if value is None:
            value = {"estado": "registered" if en else "registrado", **_payload(inputs)}
        return WorkflowNode(id=step.id, type="transform", label=label, config={"value": value})
    if kind == "condition":
        expression = str(cfg.get("expression") or "").strip()
        if not expression:
            rule = wf.approvals[0] if wf.approvals else None
            if rule is not None and rule.threshold is not None:
                expression = f"{{{{input.{ident(rule.field or 'importe')}}}}} > {rule.threshold:g}"
            else:
                return fallback("la condición no tiene expresión")
        return WorkflowNode(id=step.id, type="condition", label=label, config={"expression": expression})
    if kind == "approval":
        rule = _rule_for(wf, step)
        details = ", ".join(f"{i.name}: {{{{input.{i.name}}}}}" for i in inputs[:4])
        prompt = str(cfg.get("prompt") or "") or (
            f"Approve «{wf.title}»? {details}" if en else f"¿Aprobar «{wf.title}»? {details}"
        )
        return WorkflowNode(
            id=step.id,
            type="approval",
            label=label,
            config={
                "prompt": prompt[:2000],
                "description": step.description[:2000],
                "payload": cfg.get("payload") if isinstance(cfg.get("payload"), dict) else _payload(inputs),
                "approver_role": rule.approver_role if rule else "admin",
            },
        )
    if kind == "llm":
        data = "".join(
            f"\n{p.title}: {{{{{p.id}.output}}}}"
            for p in previous
            if p.kind in ("sql_query", "knowledge_search", "agent", "llm", "http_request", "connector_action")
        )
        prompt = str(cfg.get("prompt") or "") or f"{step.description or step.title}\n\nEntrada: {{{{input}}}}{data}"
        return WorkflowNode(
            id=step.id,
            type="llm",
            label=label,
            config={
                "model_tier": cfg.get("model_tier") or "fast",
                "system": str(cfg.get("system") or "")[:4000],
                "prompt": prompt,
                "json_output": bool(cfg.get("json_output")),
            },
        )
    if kind == "agent":
        agent = str(cfg.get("agent") or "")
        if not agent:
            agent = next((n for n, k in resolved.members.items() if k == "agent"), "")
        if not agent:
            return fallback("no hay ningún agente al que llamar")
        prompt = str(cfg.get("prompt") or "") or f"{step.description or step.title}: {_first_text_input(inputs)}"
        return WorkflowNode(id=step.id, type="agent", label=label, config={"agent": agent, "prompt": prompt})
    if kind == "knowledge_search":
        kb_id = kb(cfg.get("kb") or cfg.get("knowledge"))
        if kb_id is None:
            return fallback("no hay base de conocimiento")
        query = str(cfg.get("query") or "") or _first_text_input(inputs)
        return WorkflowNode(
            id=step.id,
            type="knowledge_search",
            label=label,
            config={"kb_ids": [kb_id], "query": query, "k": int(cfg.get("k") or 5)},
        )
    if kind == "sql_query":
        kb_id = kb(cfg.get("kb") or cfg.get("knowledge"))
        sql = str(cfg.get("sql") or "").strip()
        if kb_id is None:
            return fallback("no hay base de conocimiento para la consulta")
        if not sql:
            return fallback("falta la consulta SQL")
        return WorkflowNode(
            id=step.id,
            type="sql_query",
            label=label,
            config={"kb_id": kb_id, "sql": sql, "params": list(cfg.get("params") or [])},
        )
    if kind == "http_request":
        url = str(cfg.get("url") or "").strip()
        if not url:
            return fallback("falta la URL de la petición")
        return WorkflowNode(
            id=step.id,
            type="http_request",
            label=label,
            config={
                k: v for k, v in cfg.items() if k in ("method", "url", "headers", "query", "body", "allowed_hosts")
            },
        )
    if kind == "connector_action":
        ref = str(cfg.get("action") or "")
        spec = resolved.connector_actions.get(ref)
        if spec is None:
            return fallback(f"la acción «{ref or '?'}» necesita una conexión activa")
        return WorkflowNode(
            id=step.id,
            type="connector_action",
            label=label,
            config={
                "connection_id": str(spec["connection_id"]),
                "action": ref.split(".", 1)[-1],
                "args": cfg.get("args") if isinstance(cfg.get("args"), dict) else {},
                "requires_approval": bool(spec.get("side_effect")),
            },
        )
    if kind == "wait":
        return WorkflowNode(id=step.id, type="wait", label=label, config={"seconds": int(cfg.get("seconds") or 5)})
    if kind == "sub_workflow":
        target = str(cfg.get("workflow") or "")
        if resolved.members.get(target) != "workflow" or target == wf.name:
            return fallback(f"el flujo «{target or '?'}» no existe")
        return WorkflowNode(
            id=step.id,
            type="sub_workflow",
            label=label,
            config={"workflow": target, "args": cfg.get("args") if isinstance(cfg.get("args"), dict) else {}},
        )
    if kind == "tool":
        tool = str(cfg.get("tool") or "")
        if not tool:
            return fallback("falta la herramienta")
        return WorkflowNode(
            id=step.id,
            type="tool",
            label=label,
            config={"tool": tool, "args": cfg.get("args") or {}, "options": cfg.get("options") or {}},
        )
    return fallback(f"el tipo de paso «{kind}» necesita configuración manual")


def workflow_config(wf: PlanWorkflow, *, resolved: Resolved, warnings: list[str]) -> WorkflowConfig:
    """A linear graph from the plan steps; a condition skips the step that follows it when false (the usual
    "approve only above a threshold" pattern), joining again right after."""
    inputs = _inputs(wf)
    steps = list(wf.steps)
    if not steps or steps[0].kind != "input":
        steps.insert(0, PlanStep(id="entrada", kind="input", title="Entrada"))
    for i, step in enumerate(list(steps)):
        if step.kind != "approval":
            continue
        rule = _rule_for(wf, step)
        prev = steps[i - 1] if i > 0 else None
        if rule is not None and rule.threshold is not None and (prev is None or prev.kind != "condition"):
            taken = {s.id for s in steps}
            cond_id = "supera_umbral" if "supera_umbral" not in taken else f"supera_umbral_{i}"
            steps.insert(
                i,
                PlanStep(
                    id=cond_id,
                    kind="condition",
                    title=f"¿Más de {format_eur(rule.threshold)}?",
                    config={"expression": f"{{{{input.{ident(rule.field or 'importe')}}}}} > {rule.threshold:g}"},
                ),
            )
    if not any(s.kind == "output" for s in steps):
        steps.append(
            PlanStep(
                id="resultado" if "resultado" not in {s.id for s in steps} else "salida",
                kind="output",
                title="Resultado",
            )
        )
    # Outputs go last, in plan order.
    steps = [s for s in steps if s.kind != "output"] + [s for s in steps if s.kind == "output"][:1]

    nodes: list[WorkflowNode] = []
    for i, step in enumerate(steps):
        nodes.append(_node(wf, step, inputs=inputs, previous=steps[:i], resolved=resolved, warnings=warnings))
    edges: list[WorkflowEdge] = []
    for i in range(len(nodes) - 1):
        node, nxt = nodes[i], nodes[i + 1]
        if node.type == "condition":
            edges.append(WorkflowEdge(source=node.id, target=nxt.id, condition="true"))
            skip_to = nodes[i + 2] if i + 2 < len(nodes) else None
            if skip_to is not None:
                edges.append(WorkflowEdge(source=node.id, target=skip_to.id, condition="false"))
        else:
            edges.append(WorkflowEdge(source=node.id, target=nxt.id))
    return WorkflowConfig(
        name=wf.name,
        description=(wf.description or wf.title)[:2000],
        inputs=inputs,
        nodes=nodes,
        edges=edges,
    )


def trigger_config(wf: PlanWorkflow, *, resolved: Resolved) -> tuple[str, dict[str, Any], bool] | None:
    """(kind, config, enabled) of the workflow trigger, or ``None`` for manual workflows.

    Cron triggers start disabled (they would fire on their own as soon as the project is deployed): the user turns
    them on after reviewing the schedule.
    """
    trigger = wf.trigger
    if trigger.kind == "manual":
        return None
    if trigger.kind == "cron":
        return "cron", {"expression": trigger.schedule or "0 8 * * 1-5", "timezone": trigger.timezone}, False
    if trigger.kind == "file":
        kb_id = next(iter(resolved.kb_ids.values()), None)
        if kb_id is None:
            return None
        return "file", {"kb_id": kb_id}, True
    if trigger.kind == "connector_event":
        return None
    return trigger.kind, {}, True


