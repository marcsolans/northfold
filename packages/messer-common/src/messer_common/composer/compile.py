def _component_id(title: str, taken: set[str]) -> str:
    base = ident(title, fallback="componente", max_len=40).replace("__", "_")
    cid, n = base, 2
    while cid in taken:
        cid, n = f"{base}_{n}", n + 1
    taken.add(cid)
    return cid


def _q(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def _filters(title: str, names: list[str], dates: list[str], params: list[Any]) -> list[str]:
    where: list[str] = []
    if has_any(title, ("pendiente*", "pending", "sin pagar", "unpaid")) and "estado" in names:
        params.append("pendiente")
        where.append(f"estado = ${len(params)}")
    monthly = has_any(title, ("este mes", "del mes", "this month", "mes actual", "current month"))
    if monthly and dates and not has_any(title, ("por mes", "by month", "mensual")):
        params.append({"context": "month_start"})
        where.append(f"{_q(dates[0])} >= ${len(params)}")
    return where


def _sql_component(
    comp: PlanComponent, table: str, columns: list[dict[str, Any]]
) -> tuple[dict[str, Any], dict[str, Any]]:
    """(props, binding without kb_id) for a component over a knowledge base table."""
    names = [str(c["name"]) for c in columns if not str(c.get("name", "")).startswith("_")]
    numeric = [str(c["name"]) for c in columns if str(c.get("type", "")).lower() in NUMERIC_TYPES]
    dates = [str(c["name"]) for c in columns if str(c.get("type", "")).lower() in DATE_TYPES]
    texts = [n for n in names if n not in numeric and n not in dates]
    params: list[Any] = []
    where = _filters(comp.title, names, dates, params)
    clause = (" WHERE " + " AND ".join(where)) if where else ""
    t = _q(table)
    amount = next(
        (n for n in numeric if n in ("importe", "amount", "total", "precio")), numeric[0] if numeric else None
    )
    wants_amount = amount is not None and has_any(
        comp.title, ("importe", "amount", "cobro", "facturado", "billed", "revenue", "ingresos", "euros", "€")
    )
    if comp.type == "kpi":
        if wants_amount and amount:
            sql = f"SELECT coalesce(sum({_q(amount)}), 0) AS total FROM {t}{clause}"
            props: dict[str, Any] = {"value": "total", "format": "currency", "currency": "EUR", "decimals": 2}
        else:
            sql = f"SELECT count(*) AS total FROM {t}{clause}"
            props = {"value": "total", "format": "number"}
        if comp.description:
            props["hint"] = comp.description[:200]
        return props, {"kind": "knowledge_sql", "sql": sql, "params": params}
    if comp.type == "chart":
        group: str | None = None
        for candidate in texts:
            if has_any(comp.title, (candidate.replace("_", " "),)):
                group = candidate
        by_time = has_any(
            comp.title,
            (
                "por dia",
                "por mes",
                "por semana",
                "evolucion",
                "by day",
                "by month",
                "by week",
                "trend",
                "diari*",
                "mensual*",
            ),
        )
        if by_time and dates:
            unit = (
                "month"
                if has_any(comp.title, ("mes", "month", "mensual*"))
                else ("week" if has_any(comp.title, ("semana", "week")) else "day")
            )
            fmt = {"month": "YYYY-MM", "week": "IYYY-IW", "day": "YYYY-MM-DD"}[unit]
            x = "periodo"
            select_x = f"to_char(date_trunc('{unit}', {_q(dates[0])}), '{fmt}') AS {x}"
            order = "1"
        else:
            x = group or (texts[0] if texts else (names[0] if names else "valor"))
            select_x = f"{_q(x)}::text AS {_q(x)}"
            order = "2 DESC"
        if wants_amount and amount:
            y, agg, fmt_y = "importe", f"coalesce(sum({_q(amount)}), 0)", "currency"
        else:
            y, agg, fmt_y = "total", "count(*)", "number"
        sql = f"SELECT {select_x}, {agg} AS {y} FROM {t}{clause} GROUP BY 1 ORDER BY {order} LIMIT 31"
        return (
            {"chart": "line" if by_time else "bar", "x": x, "y": [y], "format": fmt_y, "legend": False},
            {"kind": "knowledge_sql", "sql": sql, "params": params},
        )
    shown = names[:10]
    order = f" ORDER BY {_q(dates[0])} DESC" if dates else ""
    sql = f"SELECT {', '.join(_q(n) for n in shown) or '*'} FROM {t}{clause}{order}"
    if comp.type == "record_list":
        return (
            {
                "title_field": texts[0] if texts else (shown[0] if shown else None),
                "subtitle_field": texts[1] if len(texts) > 1 else None,
                "meta_fields": [n for n in shown if n in dates or n in numeric][:4],
                "badge_field": "estado" if "estado" in names else None,
                "page_size": 10,
                "searchable": True,
            },
            {"kind": "knowledge_sql", "sql": sql, "params": params},
        )
    if comp.type == "calendar":
        if not dates:
            raise ValueError("la tabla no tiene columnas de fecha para un calendario")
        return (
            {"date_field": dates[0], "title_field": texts[0] if texts else None, "view": "month"},
            {"kind": "knowledge_sql", "sql": sql, "params": params},
        )
    columns_props = [
        {
            "key": n,
            "label": n.replace("_", " ").capitalize(),
            "format": "currency"
            if n in ("importe", "amount", "total", "precio")
            else ("number" if n in numeric else ("date" if n in dates else ("badge" if n == "estado" else "text"))),
            **({"align": "right"} if n in numeric else {}),
        }
        for n in shown
    ]
    return (
        {
            "columns": columns_props,
            "page_size": 10,
            "searchable": True,
            "empty_text": "Sin registros todavía" if not where else "No hay registros que cumplan el filtro",
        },
        {"kind": "knowledge_sql", "sql": sql, "params": params},
    )


def _layout(components: list[dict[str, Any]]) -> None:
    """Shelf packing on the 12-column grid, in order."""
    x = y = row_h = 0
    for i, comp in enumerate(components):
        w, h = _SIZES.get(comp["type"], (6, 6))
        nxt = components[i + 1]["type"] if i + 1 < len(components) else None
        if comp["type"] == "data_table" and nxt not in ("chart", "record_list"):
            w = 12
        if x + w > _GRID_COLS:
            x, y, row_h = 0, y + row_h, 0
        comp["grid"] = {"x": x, "y": y, "w": w, "h": h}
        x += w
        row_h = max(row_h, h)


def interface_definition(
    interface: PlanInterface, *, slug: str, resolved: Resolved, warnings: list[str]
) -> dict[str, Any]:
    """``interface.json`` composed from the plan's screens (components bound to the project's real data)."""
    screens: list[dict[str, Any]] = []
    taken_screens: set[str] = set()
    for screen in interface.screens:
        taken: set[str] = set()
        components: list[dict[str, Any]] = []
        for comp in screen.components:
            built = _component(comp, taken=taken, resolved=resolved, warnings=warnings)
            if built is not None:
                components.append(built)
        if not components:
            warnings.append(f"La pantalla «{screen.title}» no tiene componentes con datos; no se ha creado")
            continue
        _layout(components)
        screens.append(
            {
                "id": _component_id(screen.title, taken_screens),
                "title": screen.title[:80],
                "layout": "grid",
                "components": components,
            }
        )
    if interface.kind == "chat":
        chat = next((c for s in screens for c in s["components"] if c["type"] == "chat"), None)
        if chat is None:
            raise ValueError("Una interfaz de chat necesita un componente de chat con un agente")
        chat["grid"] = {"x": 0, "y": 0, "w": 12, "h": 12}
        screens = [{"id": "chat", "title": interface.title[:80], "layout": "grid", "components": [chat]}]
    if not screens:
        raise ValueError("La interfaz no tiene ninguna pantalla con componentes válidos")
    return {
        "version": 1,
        "name": interface.title[:120],
        "slug": slug,
        "kind": interface.kind,
        "description": interface.justification[:500],
        "auth": {"required": interface.kind == "app", "roles": []},
        "screens": screens,
    }


def _component(
    comp: PlanComponent, *, taken: set[str], resolved: Resolved, warnings: list[str]
) -> dict[str, Any] | None:
    title = comp.title[:120]
    source = comp.source.strip()
    base: dict[str, Any] = {"id": _component_id(title, taken), "type": comp.type, "title": title}
    if comp.description:
        base["description"] = comp.description[:300]
    if comp.type == "approvals_inbox":
        return {
            **base,
            "props": {"page_size": 10},
            "binding": {"kind": "approvals", "project": "current", "status": "pending"},
        }
    if source.startswith("kb:"):
        ref = source[3:]
        kb_name, _, table = ref.partition(".")
        kb_id = resolved.kb_ids.get(kb_name)
        if kb_id is None:
            warnings.append(f"«{title}»: la base de conocimiento «{kb_name}» no existe")
            return None
        if comp.type == "file_upload":
            return {**base, "props": {"kb_id": kb_id, "multiple": True, "max_mb": 20}}
        if not table:
            if comp.type in ("data_table", "record_list"):
                return {
                    **base,
                    "props": {},
                    "binding": {"kind": "knowledge_search", "kb_ids": [kb_id], "query": "", "query_input": "search"},
                }
            warnings.append(f"«{title}»: indica la tabla de «{kb_name}»")
            return None
        columns = resolved.tables.get(f"{kb_name}.{table}")
        if not columns:
            warnings.append(f"«{title}»: la tabla «{table}» no existe en «{kb_name}»")
            return None
        if comp.type not in ("data_table", "chart", "kpi", "record_list", "calendar"):
            warnings.append(f"«{title}»: un componente {comp.type} no se puede enlazar a una tabla")
            return None
        try:
            props, binding = _sql_component(comp, table, columns)
        except ValueError as exc:
            warnings.append(f"«{title}»: {exc}")
            return None
        return {**base, "props": props, "binding": {**binding, "kb_id": kb_id}}
    if source.startswith("agent:"):
        agent = source[6:]
        if resolved.members.get(agent) != "agent":
            warnings.append(f"«{title}»: el agente «{agent}» no existe")
            return None
        if comp.type == "chat":
            greeting = resolved.agent_greetings.get(agent) or "Hola, ¿en qué puedo ayudarte?"
            return {
                **base,
                "props": {"greeting": greeting[:1000], "suggestions": []},
                "binding": {"kind": "agent", "workforce": agent},
            }
        if comp.type == "action_button":
            return {
                **base,
                "props": {"label": title[:60], "success_message": "Hecho"},
                "binding": {"kind": "agent", "workforce": agent, "prompt": (comp.description or title)[:8000]},
            }
        if comp.type == "form":
            return {
                **base,
                "props": {
                    "fields": [{"name": "mensaje", "label": "Mensaje", "type": "textarea", "required": True}],
                    "submit_label": "Enviar",
                },
                "binding": {"kind": "agent", "workforce": agent, "prompt": "{{form.mensaje}}"},
            }
        warnings.append(f"«{title}»: un componente {comp.type} no se puede enlazar a un agente")
        return None
    if source.startswith("workflow:"):
        workflow = source[9:]
        if resolved.members.get(workflow) != "workflow":
            warnings.append(f"«{title}»: el flujo «{workflow}» no existe")
            return None
        inputs = resolved.workflow_inputs.get(workflow, [])
        if comp.type == "form":
            fields = [
                {
                    "name": i.name,
                    "label": (i.description or i.name.replace("_", " ")).capitalize()[:120],
                    "type": "number" if i.type == "number" else "text",
                    "required": i.required,
                    **({"min": 0} if i.type == "number" else {}),
                }
                for i in inputs
                if i.type in ("string", "number")
            ] or [{"name": "mensaje", "label": "Mensaje", "type": "textarea", "required": True}]
            return {
                **base,
                "props": {"fields": fields, "submit_label": "Enviar", "success_message": "Solicitud enviada"},
                "binding": {
                    "kind": "workflow",
                    "workforce": workflow,
                    "input_mapping": {f["name"]: f"$form.{f['name']}" for f in fields},
                },
            }
        if comp.type == "action_button":
            return {
                **base,
                "props": {"label": title[:60], "success_message": "Flujo iniciado"},
                "binding": {"kind": "workflow", "workforce": workflow, "input_mapping": {}},
            }
        warnings.append(f"«{title}»: un componente {comp.type} no se puede enlazar a un flujo")
        return None
    warnings.append(f"«{title}»: no tiene origen de datos ({comp.type}); no se ha añadido")
    return None


