"""Run a project locally like its export does: ``messer.platform.standalone`` (tracing, model proxy, knowledge,
files) plus one engine HTTP server (``python -m messer.server``) per workforce member.

Members never get provider keys: model calls go through the local platform, which uses ``ANTHROPIC_API_KEY`` when
set and a labelled offline model otherwise (exactly as in an exported project)."""

from __future__ import annotations

import os
import secrets
import shutil
import signal
import socket
import subprocess
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path

import httpx
from dotenv import dotenv_values

from .scaffold import discover_members

PROVIDER_KEYS = ("ANTHROPIC_API_KEY", "AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_SESSION_TOKEN")


class LocalError(Exception):
    pass


def port_free(port: int) -> bool:
    with socket.socket() as s:
        try:
            s.bind(("127.0.0.1", port))
        except OSError:
            return False
    return True


def next_free(start: int, taken: set[int]) -> int:
    port = start
    while port in taken or not port_free(port):
        port += 1
        if port > 65000:
            raise LocalError("No hay puertos libres")
    taken.add(port)
    return port


def entrypoint_source(name: str, module_file: str, attr: str) -> str:
    """Loader that imports the member as a package (relative imports work), like the export's entrypoints."""
    module = f"workforce.{name}.{module_file.removesuffix('.py')}"
    return (
        "# Generated by `messer start`: loads the member as a package for `python -m messer.server`.\n"
        "import importlib\nimport os\nimport sys\nfrom pathlib import Path\n\n"
        'PROJECT_DIR = Path(os.environ.get("MESSER_PROJECT_DIR") or Path(__file__).resolve().parents[2])\n'
        "if str(PROJECT_DIR) not in sys.path:\n    sys.path.insert(0, str(PROJECT_DIR))\n\n"
        f"runnable = getattr(importlib.import_module({module!r}), {attr!r})\n"
    )


@dataclass(slots=True)
class Service:
    name: str
    port: int
    command: list[str]
    env: dict[str, str]
    process: subprocess.Popen[bytes] | None = None
    kind: str = "member"


@dataclass(slots=True)
class LocalStack:
    project_dir: Path
    python: str
    token: str = field(default_factory=lambda: secrets.token_urlsafe(24))
    org_id: str = "local"
    project_id: str = "local"
    services: list[Service] = field(default_factory=list)

    @property
    def state_dir(self) -> Path:
        return self.project_dir / ".messer" / "state"

    @property
    def platform(self) -> Service | None:
        return next((s for s in self.services if s.kind == "platform"), None)

    def base_env(self) -> dict[str, str]:
        env = {k: v for k, v in os.environ.items() if not k.startswith("MESSER_STANDALONE_")}
        for key, value in dotenv_values(self.project_dir / ".env").items():
            if value is not None:
                env[key] = value
        env["PYTHONUNBUFFERED"] = "1"
        env["MESSER_PROJECT_DIR"] = str(self.project_dir)
        return env

    def add_platform(self, port: int) -> Service:
        env = self.base_env()
        data_dir = self.project_dir / ".messer" / "data"
        data_dir.mkdir(parents=True, exist_ok=True)
        self.state_dir.mkdir(parents=True, exist_ok=True)
        env.update(
            {
                "MESSER_STANDALONE_TOKEN": self.token,
                "MESSER_STANDALONE_DATA_DIR": str(data_dir),
                "MESSER_STANDALONE_STATE_DIR": str(self.state_dir),
                "MESSER_STANDALONE_PUBLIC_URL": f"http://127.0.0.1:{port}",
                "MESSER_ORG_ID": self.org_id,
                "MESSER_PROJECT_ID": self.project_id,
            }
        )
        service = Service(
            name="platform",
            port=port,
            kind="platform",
            command=[self.python, "-m", "messer.platform.standalone", "--host", "127.0.0.1", "--port", str(port)],
            env=env,
        )
        self.services.append(service)
        return service

    def member_env(self) -> dict[str, str]:
        env = self.base_env()
        for key in PROVIDER_KEYS:
            env.pop(key, None)  # model calls go through the local platform
        platform = self.platform
        if platform is not None:
            env.update(
                {
                    "MESSER_API_HOST": f"http://127.0.0.1:{platform.port}/",
                    "MESSER_API_KEY": self.token,
                    "MESSER_ORG_ID": self.org_id,
                    "MESSER_PROJECT_ID": self.project_id,
                }
            )
        env.pop("MESSER_API_URL", None)
        env.pop("MESSER_PROFILE", None)
        return env

    def add_members(self, ports: dict[str, int], only: list[str] | None = None) -> list[Service]:
        members = discover_members(self.project_dir)
        if only:
            unknown = sorted(set(only) - {m[0] for m in members})
            if unknown:
                raise LocalError(f"No existe en workforce/: {', '.join(unknown)}")
            members = [m for m in members if m[0] in only]
        if not members:
            raise LocalError("El proyecto no tiene agentes ni flujos (workforce/<nombre>/messer.yaml)")
        entry_dir = self.project_dir / ".messer" / "entrypoints"
        entry_dir.mkdir(parents=True, exist_ok=True)
        added: list[Service] = []
        for name, _kind, fqn in members:
            module_file, _, attr = fqn.partition("::")
            entry = entry_dir / f"entry_{name}.py"
            entry.write_text(entrypoint_source(name, module_file, attr), encoding="utf-8")
            service = Service(
                name=name,
                port=ports[name],
                command=[
                    self.python,
                    "-m",
                    "messer.server",
                    "--import_spec",
                    f"{entry}::runnable",
                    "--host",
                    "127.0.0.1",
                    "--port",
                    str(ports[name]),
                ],
                env=self.member_env(),
            )
            self.services.append(service)
            added.append(service)
        return added

    def start(self, service: Service, log_dir: Path | None = None) -> None:
        stdout = None
        if log_dir is not None:
            log_dir.mkdir(parents=True, exist_ok=True)
            stdout = (log_dir / f"{service.name}.log").open("ab")
        service.process = subprocess.Popen(  # noqa: S603 - our own interpreter and module
            service.command,
            cwd=self.project_dir,
            env=service.env,
            stdout=stdout,
            stderr=subprocess.STDOUT if stdout else None,
            start_new_session=True,
        )

    def wait_healthy(self, service: Service, timeout_s: float = 60.0) -> None:
        deadline = time.monotonic() + timeout_s
        url = f"http://127.0.0.1:{service.port}/healthcheck"
        while time.monotonic() < deadline:
            if service.process is not None and service.process.poll() is not None:
                raise LocalError(f"{service.name} terminó al arrancar (código {service.process.returncode})")
            try:
                if httpx.get(url, timeout=2.0).status_code == 200:
                    return
            except httpx.HTTPError:
                pass
            time.sleep(0.2)
        raise LocalError(f"{service.name} no responde en {url}")

    def stop(self) -> None:
        for service in reversed(self.services):
            proc = service.process
            if proc is None or proc.poll() is not None:
                continue
            try:
                os.killpg(proc.pid, signal.SIGTERM)
            except (ProcessLookupError, PermissionError):
                proc.terminate()
        deadline = time.monotonic() + 10
        for service in self.services:
            proc = service.process
            if proc is None:
                continue
            try:
                proc.wait(timeout=max(0.1, deadline - time.monotonic()))
            except subprocess.TimeoutExpired:
                try:
                    os.killpg(proc.pid, signal.SIGKILL)
                except (ProcessLookupError, PermissionError):
                    proc.kill()
                proc.wait()


def default_python(project_dir: Path) -> str:
    """The project's own virtualenv when it has one (its dependencies), else the CLI's interpreter."""
    for candidate in (project_dir / ".venv" / "bin" / "python", project_dir / ".venv" / "Scripts" / "python.exe"):
        if candidate.is_file():
            return str(candidate)
    return sys.executable or shutil.which("python3") or "python3"
